export function paperCalendarState(date: string, inRange: boolean): CalendarState {
  if (!inRange) return date < paperCalendar.start ? 'beforeRecord' : 'future';
  if (date > paperCalendar.today) return 'future';
  return paperCalendar.special[date] ?? 'ok';
}
